local function translate_which_key_desc(desc)
  local normalized = desc:gsub("^:%s*", "")
  local translated = which_key_desc_zh[desc] or which_key_desc_zh[normalized]
  if translated then
    return translated
  end

  local keymap_count = desc:match("^(%d+) keymaps?$")
  if keymap_count then
    return keymap_count .. " 个快捷键"
  end

  local mark_file = desc:match("^file: (.+)$")
  if mark_file then
    return "文件：" .. mark_file
  end

  return desc
end

local function patch_which_key_footer_help()
  local text = require("which-key.text")
  if text._zh_footer_help_patched then
    return
  end

  local append = text.append
  local footer_zh = {
    [" close"] = " 关闭",
    [" back"] = " 返回",
    [" scroll"] = " 滚动",
  }

  function text:append(value, opts)
    if type(value) == "string" then
      value = footer_zh[value] or value
    end

    return append(self, value, opts)
  end

  text._zh_footer_help_patched = true
end

return {
  "folke/which-key.nvim",
  event = "VeryLazy",
  opts = {
    replace = {
      desc = {
        [100] = translate_which_key_desc,
      },
    },
  },
  config = function(_, opts)
    require("which-key").setup(opts)
    patch_which_key_footer_help()
  end,
  keys = {
    {
      "<leader>?",
      function()
        require("which-key").show({ global = false })
      end,
      desc = "显示当前缓冲区快捷键",
    },
  },
}
